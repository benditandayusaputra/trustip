package main

import (
	"slices"
	"testing"
)

type scanCase struct {
	name   string
	source string
	want   []int
}

func runScanCases(t *testing.T, scan func([]byte) []int, cases []scanCase) {
	t.Helper()
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got := scan([]byte(tc.source))
			if !slices.Equal(got, tc.want) {
				t.Fatalf("lines = %v, want %v", got, tc.want)
			}
		})
	}
}

func TestScanGoComments(t *testing.T) {
	cases := []scanCase{
		{"line comment is found", "package a\n\n// note\nfunc f() {}\n", []int{3}},
		{"block comment is found", "package a\n\nfunc f() { /* x */ }\n", []int{3}},
		{"slashes inside string are not comments", "package a\n\nconst u = \"https://x.id\"\n", nil},
		{"build directive is allowed", "//go:build linux\n\npackage a\n", nil},
		{"embed directive is allowed", "package a\n\nimport _ \"embed\"\n\n//go:embed x.sql\nvar s string\n", nil},
		{"generated file is skipped", "// Code generated by sqlc. DO NOT EDIT.\n\npackage a\n\n// x\n", []int{}},
	}
	runScanCases(t, mustScanGo(t), cases)
}

func mustScanGo(t *testing.T) func([]byte) []int {
	t.Helper()
	return func(source []byte) []int {
		lines, err := scanGoComments(source)
		if err != nil {
			t.Fatalf("scan go: %v", err)
		}
		return lines
	}
}

func TestScanGoComments_InvalidSource_ReturnsError(t *testing.T) {
	if _, err := scanGoComments([]byte("package")); err == nil {
		t.Fatal("expected parse error")
	}
}

func TestScanSQLComments(t *testing.T) {
	cases := []scanCase{
		{"line comment is found", "SELECT 1;\n-- why\n", []int{2}},
		{"trailing comment is found", "SELECT 1; -- why\n", []int{1}},
		{"block comment is found", "SELECT /* x */ 1;\n", []int{1}},
		{"sqlc annotation is allowed", "-- name: GetUser :one\nSELECT 1;\n", nil},
		{
			"goose markers are allowed",
			"-- +goose Up\n-- +goose StatementBegin\nSELECT 1;\n-- +goose StatementEnd\n",
			nil,
		},
		{"dashes inside string are not comments", "SELECT '--x', 'it''s /* y */';\n", nil},
		{"dashes inside dollar quote are not comments", "SELECT $f$ -- x $f$;\n", nil},
		{"backslash in string does not escape quote", "SELECT 'a\\';\n-- z\n", []int{2}},
	}
	runScanCases(t, scanSQLComments, cases)
}

func TestScanCSSComments(t *testing.T) {
	cases := []scanCase{
		{"block comment is found", "a {\n  /* x */\n  color: red;\n}\n", []int{2}},
		{"comment marker inside string is not a comment", "a { content: \"/* x */\"; }\n", nil},
		{"url with slashes is not a comment", "a { background: url(https://x.id/a.png); }\n", nil},
	}
	runScanCases(t, scanCSSComments, cases)
}

func TestScanMarkupComments(t *testing.T) {
	cases := []scanCase{
		{"html comment is found", "<div>\n<!-- x -->\n</div>\n", []int{2}},
		{"two comments are both found", "<!-- a -->\n<p></p>\n<!-- b -->\n", []int{1, 3}},
		{"plain markup has none", "<p>a -- b</p>\n", nil},
	}
	runScanCases(t, scanMarkupComments, cases)
}

func TestScanSvelteStyleComments(t *testing.T) {
	cases := []scanCase{
		{"comment in style block is found", "<p>x</p>\n<style>\n  /* x */\n</style>\n", []int{3}},
		{"comment-like text outside style is ignored", "<p>/* x */</p>\n", nil},
	}
	runScanCases(t, scanSvelteStyleComments, cases)
}

func TestScanHashComments(t *testing.T) {
	cases := []scanCase{
		{"full line comment is found", "a: 1\n# x\n", []int{2}},
		{"trailing comment is found", "a: 1 # x\n", []int{1}},
		{"hash inside quotes is not a comment", "a: \"x # y\"\nb: 'z # w'\n", nil},
		{"hash without leading space is not a comment", "url: https://x.id/#top\n", nil},
		{"shebang on first line is allowed", "#!/bin/sh\necho hi\n", nil},
		{"shebang after first line is a comment", "echo hi\n#!/bin/sh\n", []int{2}},
	}
	runScanCases(t, scanHashComments, cases)
}

func TestScannerFor_UnknownExtension_ReturnsError(t *testing.T) {
	if _, err := scannerFor("app/src/x.unknown"); err == nil {
		t.Fatal("expected unknown file type error")
	}
}

func TestScannerFor_MarkdownIsExempt(t *testing.T) {
	scan, err := scannerFor("docs/01-PRD.md")
	if err != nil {
		t.Fatalf("scannerFor: %v", err)
	}
	lines, err := scan([]byte("<!-- x -->\n"))
	if err != nil || len(lines) > 0 {
		t.Fatalf("lines = %v, err = %v, want none", lines, err)
	}
}
